/**
 * Build every runtime artifact from the TypeScript sources.
 *
 * Two targets, two rules:
 *
 *   - **Browser** (`client/client.js`): DSH's module loader wants one
 *     `window.__ModuleLoader__.load({ id, factory(require) })` module per
 *     package, so esbuild emits a CJS bundle and this script wraps it in that
 *     envelope. React is never imported: the loader supplies it, and the
 *     wrapper puts it in scope as `React`/`h`; `.tsx` sources compile through
 *     `jsxFactory: h` and `jsxFragment: Fragment`, so JSX needs no runtime.
 *   - **Host** (`index.js`): plain ESM for Node, transpiled only (no bundling),
 *     so `node:` imports stay intact.
 *
 * Type checking is a separate command (`tsc --noEmit`): esbuild strips types
 * without checking them.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve as resolvePath } from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

const here = dirname(fileURLToPath(import.meta.url))
const root = resolvePath(here, '..')
const manifest = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))

const banner = '/** Generated by scripts/build.mjs from client/src — edit the TypeScript sources. */'

/**
 * Bundle the Client half into the loader envelope.
 * @returns {Promise<{ out: string, bytes: number }>} written artifact.
 */
async function buildClient() {
  const result = await build({
    entryPoints: [join(root, 'client', 'src', 'main.ts')],
    bundle: true,
    write: false,
    format: 'cjs',
    platform: 'browser',
    target: 'es2022',
    logLevel: 'warning',
    legalComments: 'none',
    jsx: 'transform',
    jsxFactory: 'h',
    jsxFragment: 'Fragment',
  })
  const body = result.outputFiles[0]?.text ?? ''
  const artifact = [
    banner,
    'window.__ModuleLoader__.load({',
    `  id: ${JSON.stringify(manifest.name)},`,
    '  factory(require) {',
    "    const React = require('react')",
    '    const h = React.createElement',
    '    const Fragment = React.Fragment',
    '    const module = { exports: {} }',
    '    const exports = module.exports',
    '    ;(function (module, exports, require, React, h) {',
    body,
    '    })(module, exports, require, React, h)',
    '    return module.exports',
    '  },',
    '})',
    '',
  ].join('\n')
  const out = join(root, 'client', 'client.js')
  writeFileSync(out, artifact, 'utf8')
  return { out, bytes: Buffer.byteLength(artifact, 'utf8') }
}

/**
 * Transpile the Host half in place (no bundling, ESM preserved).
 * @returns {Promise<{ out: string, bytes: number }>} written artifact.
 */
async function buildHost() {
  const out = join(root, 'index.js')
  await build({
    entryPoints: [join(root, 'index.ts')],
    outfile: out,
    bundle: false,
    format: 'esm',
    platform: 'node',
    target: 'node20',
    logLevel: 'warning',
    legalComments: 'none',
    banner: { js: '/** Generated by scripts/build.mjs from index.ts — edit the TypeScript source. */' },
  })
  return { out, bytes: readFileSync(out).byteLength }
}

const client = await buildClient()
const host = await buildHost()
console.log(
  `built client/client.js (${(client.bytes / 1024).toFixed(1)} KiB) and index.js (${(host.bytes / 1024).toFixed(1)} KiB)`,
)
